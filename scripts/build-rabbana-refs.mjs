import { readFileSync, writeFileSync } from "node:fs";
const surahs = JSON.parse(readFileSync("lang/src/14-surahs.json","utf8"));
const w = {}; new Function("window", readFileSync("quran/rabbanas.js","utf8"))(w);

/* The reference is a sūrah name and an āyah number. The name is taken from the
   sūrah translations rather than written again, so the Rabbanā list and the
   Qur'an list can never disagree about what a sūrah is called. */
const N = {
  "Al-Baqarah":2, "Āl ʿImrān":3, "Al-Māʾidah":5, "Al-Aʿrāf":7, "Yūnus":10,
  "Ibrāhīm":14, "Al-Kahf":18, "Ṭā Hā":20, "Al-Muʾminūn":23, "Al-Furqān":25,
  "Fāṭir":35, "Ghāfir":40, "Al-Ḥashr":59, "Al-Mumtaḥanah":60, "At-Taḥrīm":66,
};
const out = { _note: "key: [Urdu, Gujarati, Arabic]. Generated by scripts — the sūrah name comes from 14-surahs.json so the two lists cannot disagree. Āyah numbers stay in ASCII so num() puts them in the reader's own digits." };
let bad = 0;
for (const r of w.RABBANAS) {
  const m = r.ref.match(/^(.+?)\s+([\d–\-]+)$/);
  const n = m && N[m[1]];
  if (!n) { console.log("  unmapped:", r.ref); bad++; continue; }
  const names = surahs[`surah.${n}.name`];
  out[`rabbana.${r.n}.ref`] = names.map(name => `${name} ${m[2]}`);
}
writeFileSync("lang/src/17-rabbanas.json", JSON.stringify(out, null, 1) + "\n");
console.log(`${Object.keys(out).length - 1} rabbanā refs written${bad ? `, ${bad} UNMAPPED` : ""}`);
