/* The madrasah's year, copied out of the website rather than retyped.
 *
 * MAD_CLOSURES and MAD_EVENTS are edited once a year, in index.html, by
 * whoever has the madrasah's calendar in front of them. Two copies of that
 * would drift apart within one term and a parent would plan a trip around the
 * wrong week — so this lifts them across verbatim and the app imports the
 * result. Nothing here is rewritten; if the shape in the website changes, this
 * fails loudly rather than producing half a year.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const html = fs.readFileSync(path.resolve(root, "..", "index.html"), "utf8");

const grab = (name, opener) => {
  const i = html.indexOf(`const ${name} = ${opener}`);
  if (i < 0) { console.error(`${name} is not in index.html any more`); process.exit(1); }
  const start = html.indexOf(opener, i);
  const close = opener === "[" ? "]" : "}";
  let depth = 0, end = -1;
  for (let j = start; j < html.length; j++) {
    if (html[j] === opener) depth++;
    else if (html[j] === close && --depth === 0) { end = j + 1; break; }
  }
  if (end < 0) { console.error(`${name} is not closed`); process.exit(1); }
  return html.slice(start, end);
};

const year = grab("MAD_YEAR", "{");
const closures = grab("MAD_CLOSURES", "[");
const events = grab("MAD_EVENTS", "[");

/* Parsed here so a typo in the website is caught by this script rather than by
 * a parent looking at a blank calendar. */
for (const [name, src] of [["MAD_YEAR", year], ["MAD_CLOSURES", closures], ["MAD_EVENTS", events]]) {
  try { new Function(`return ${src}`)(); }
  catch (e) { console.error(`${name} does not parse: ${e.message}`); process.exit(1); }
}
const n = new Function(`return ${closures}`)().length;
const m = new Function(`return ${events}`)().length;
if (!n || !m) { console.error("a list came back empty"); process.exit(1); }

const out = `/* GENERATED by scripts/extract-madrasah.mjs — do not edit.
 *
 * The madrasah's year, lifted verbatim from the website's index.html, which is
 * where it is edited once a year. Re-run the script after it changes there.
 */
export const MAD_YEAR = ${year};

export const MAD_CLOSURES = ${closures};

export const MAD_EVENTS = ${events};
`;
fs.writeFileSync(path.resolve(root, "src/madrasah-data.js"), out);
console.log(`madrasah-data.js written — ${n} closures, ${m} Islamic dates, year ${JSON.parse(year.replace(/(\w+):/g, '"$1":').replace(/'/g, '"')).from} to ${JSON.parse(year.replace(/(\w+):/g, '"$1":').replace(/'/g, '"')).to}`);
