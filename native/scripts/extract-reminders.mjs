/**
 * Lifts the home screen's reminders out of the web app, verbatim.
 *
 * Fifty-four of them, each with a `when(context)` that decides whether today is
 * the day — the white days, the last hour of Jumuʿah, the night of 15 Shaʿbān.
 * Retyping those predicates would be fifty-four chances to get a date wrong, so
 * the array is copied out as source between its own two markers and written as
 * a module. The helpers it closes over come with it.
 *
 *   node scripts/extract-reminders.mjs
 */
import fs from "node:fs"; import path from "node:path";
const ROOT = path.resolve(import.meta.dirname, "../..");
const src = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");

const grab = (startRe, endRe) => {
  const a = src.search(startRe);
  if (a < 0) throw new Error("not found: " + startRe);
  const b = src.indexOf(endRe, a);
  if (b < 0) throw new Error("no end for: " + startRe);
  return src.slice(a, b + endRe.length);
};

const suhoor   = grab(/^const suhoorNote = /m, ': "";');
const helpers  = grab(/^const hIs = /m, "\n") + grab(/^const tIs = /m, "\n");
const calendar = grab(/^const CALENDAR_DAYS = \[/m, "\n];");
const reminders = grab(/^const REMINDERS = \[/m, "\n];");

const out = `/* GENERATED by scripts/extract-reminders.mjs — do not edit.
 *
 * The home screen's reminders, copied out of the web app's index.html as
 * source so the two cannot disagree about when the white days fall or when the
 * last hour of Jumuʿah is. Edit them there and run the script again.
 */

/* num() and hm12() are the web app's own formatters; the native equivalents
 * are passed in beside the translator. */
${suhoor.replace(/\bt\(/g, "T(").replace(/num\(hm12\(/g, "PRETTY((")}
${helpers}
${calendar}
${reminders.replace(/\bt\(/g, "T(")}

/* The translator is passed in rather than reached for: these definitions were
 * written against a global t() the web app has and this app does not. */
let T = (k, en) => en;
let PRETTY = x => x;
export function setReminderTranslator(fn, pretty) { T = fn; if (pretty) PRETTY = pretty; }

/* The web app's own helpers, which these definitions close over. */
const DOW = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
function fullDow(n) { return T("date.fulldow." + n, DOW[n]); }

export { REMINDERS };
`;
const dest = path.resolve(import.meta.dirname, "../src/reminders-data.js");
fs.writeFileSync(dest, out);
const n = (reminders.match(/\{\s*id:/g) || []).length + (calendar.match(/\{\s*id:/g) || []).length;
/* A reminder that calls a helper this file does not define is a blank home
 * screen on somebody's phone, so it fails here instead of there. Comments are
 * stripped first — prose about num() is not a call to num(). */
const code = out.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
const declared = new Set([...code.matchAll(/(?:function|const|let|var)\s+([A-Za-z_$][\w$]*)/g)].map(m => m[1]));
const BUILTIN = /^(if|for|while|switch|catch|return|typeof|new|RegExp|Date|String|Number|Math|Array|Object|JSON|parseInt|parseFloat|isNaN)$/;
const METHOD = /[.?]\s*$/;
const called = [...code.matchAll(/(.?)\b([A-Za-z_$][\w$]*)\s*\(/g)]
  .filter(m => m[1] !== ".")                       // a method call is somebody else's problem
  .map(m => m[2]);
const unknown = [...new Set(called)].filter(k => !declared.has(k) && !BUILTIN.test(k));
if (unknown.length) {
  console.error("These helpers are used but not defined here: " + unknown.join(", "));
  console.error("Add them to the generated preamble in this script, or the home screen will throw.");
  process.exit(1);
}
console.log(`wrote src/reminders-data.js — ${n} reminders, no undefined helpers`);
